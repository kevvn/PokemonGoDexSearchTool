// Precomputed lookup map from Pokémon ID to its complete sorted family IDs
const FAMILY_MAP = new Map();

// 1. Populate standard families
STANDARD_FAMILIES.forEach(([start, end]) => {
  const family = [];
  for (let id = start; id <= end; id++) {
    family.push(id);
  }
  family.sort((a, b) => a - b);
  family.forEach(id => {
    FAMILY_MAP.set(id, family);
  });
});

// 2. Overwrite with special cross-gen / branching / baby lines
SPECIAL_FAMILIES.forEach(family => {
  const sorted = [...new Set(family)].sort((a, b) => a - b);
  sorted.forEach(id => {
    FAMILY_MAP.set(id, sorted);
  });
});

/**
 * Returns the complete array of evolutionary family IDs for a given Pokémon ID.
 * @param {number} pokemonId 
 * @returns {number[]} Array of family IDs (sorted ascending)
 */
export function getFamilyIds(pokemonId) {
  const idNum = Number(pokemonId);
  const found = FAMILY_MAP.get(idNum);
  if (found) return found;
  return [idNum];
}

export default getFamilyIds;
